inline const Line* Crossed(int zone, const Point& sceneStart, const Point& sceneEnd, bool mirrorX)
{
    const Point a = FFXICoordinateFrame::SceneToNativeDat(sceneStart, mirrorX);
    const Point b = FFXICoordinateFrame::SceneToNativeDat(sceneEnd, mirrorX);
    const Line* found = nullptr;
    float first = 2;
    for (const Line& line : lines)
    {
        if (line.fromZone != zone) continue;
        const float start = (a[0]-line.threshold[0])*line.outward[0] + (a[2]-line.threshold[2])*line.outward[2];
        const float end = (b[0]-line.threshold[0])*line.outward[0] + (b[2]-line.threshold[2])*line.outward[2];
        if (!(start < 0 && end >= 0)) continue;
        const float t = -start / (end-start);
        const float x = a[0] + t*(b[0]-a[0]) - line.threshold[0];
        const float z = a[2] + t*(b[2]-a[2]) - line.threshold[2];
        const float y = a[1] + t*(b[1]-a[1]) - line.threshold[1];
        if (std::fabs(x*line.outward[2] - z*line.outward[0]) > line.halfWidth || std::fabs(y) > 4) continue;
        if (t < first) { first = t; found = &line; }
    }
    return found;
}

inline float ArrivalYaw(const Line& line, bool mirrorX)
{
    return FFXICoordinateFrame::NativeDatHeadingToScene(line.heading, mirrorX) - 1.57079632679f;
}
